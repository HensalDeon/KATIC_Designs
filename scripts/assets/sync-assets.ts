/**
 * Copies images and videos extracted from the original site into the project under semantic
 * names, then generates `src/content/media.ts` (typed static imports).
 *
 * Requires `reference/original/assets/` (git-ignored; see docs/MIGRATION_PLAN.md §6, Phase 0).
 * Usage: pnpm assets:sync
 */
import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import * as prettier from "prettier";

import { MEDIA_MAP, UNUSED_SOURCE_KEYS, VIDEO_MAP } from "./media-map";
import { toIdentifier, validateMediaMap } from "./validate-media-map";

const ROOT = process.cwd();
const SOURCE_DIR = path.join(ROOT, "reference/original/assets");
const IMAGE_OUT = path.join(ROOT, "src/assets/images");
const VIDEO_OUT = path.join(ROOT, "public/video");
const MANIFEST = path.join(ROOT, "src/content/media.ts");

async function main(): Promise<void> {
  const files = await readdir(SOURCE_DIR).catch(() => {
    throw new Error(
      `Missing ${path.relative(ROOT, SOURCE_DIR)}. Restore the reference folder first.`,
    );
  });
  const availableKeys = new Set(
    files.filter((f) => f.startsWith("img-") && f.endsWith(".webp")).map((f) => f.slice(4, -5)),
  );

  const problems = validateMediaMap(MEDIA_MAP, UNUSED_SOURCE_KEYS, availableKeys);
  if (problems.length > 0) {
    throw new Error(`Media map is invalid:\n  - ${problems.join("\n  - ")}`);
  }

  // Images: rebuild the output folder from scratch so renames never leave stale files behind.
  await rm(IMAGE_OUT, { recursive: true, force: true });
  for (const entry of MEDIA_MAP) {
    const target = path.join(IMAGE_OUT, `${entry.id}.webp`);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(path.join(SOURCE_DIR, `img-${entry.key}.webp`), target);
  }

  await mkdir(VIDEO_OUT, { recursive: true });
  for (const video of VIDEO_MAP) {
    await copyFile(path.join(SOURCE_DIR, video.source), path.join(VIDEO_OUT, video.target));
  }

  await mkdir(path.dirname(MANIFEST), { recursive: true });
  await writeFile(MANIFEST, await renderManifest());

  console.log(
    `Synced ${MEDIA_MAP.length} images, ${VIDEO_MAP.length} videos; skipped ${UNUSED_SOURCE_KEYS.length} unused.`,
  );
  console.log(`Wrote ${path.relative(ROOT, MANIFEST)}`);
}

async function renderManifest(): Promise<string> {
  const entries = [...MEDIA_MAP].sort((a, b) => a.id.localeCompare(b.id));
  const imports = entries
    .map((e) => `import ${toIdentifier(e.id)} from "@/assets/images/${e.id}.webp";`)
    .join("\n");
  const records = entries
    .map(
      (e) =>
        `${JSON.stringify(e.id)}: { image: ${toIdentifier(e.id)}, description: ${JSON.stringify(e.description)}, sourceKey: ${JSON.stringify(e.key)} },`,
    )
    .join("\n");

  const source = `/**
 * AUTO-GENERATED by scripts/assets/sync-assets.ts. Do not edit by hand.
 * Edit scripts/assets/media-map.ts and run \`pnpm assets:sync\`.
 */
${imports}
import type { MediaAsset } from "@/lib/media/types";

export const media = {
${records}
} as const satisfies Record<string, MediaAsset>;

export type MediaId = keyof typeof media;
`;
  const options = await prettier.resolveConfig(MANIFEST);
  return prettier.format(source, { ...options, filepath: MANIFEST });
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
